'use strict';

// The four shell calls of SPEC §9, plus verify/publish. This module owns every
// exec of a pipeline script; the worker never shells out directly.

const fs = require('fs');
const path = require('path');
const { spawnSync } = require('child_process');

const { createClient, childEnv } = require('./kaggle');

// The MiniMax H3 Community Licence (section III.3.b) asks for an AI-generation identifier inside
// every produced file. It has to travel with the file, not sit next to it, so it is written into the
// mp4 metadata as the last step before the file is served.
const AI_ID_TITLE = 'MiniMax H3';
const AI_ID_ARTIST = 'h3-kaggle-studio';

function stampMp4(file, exec, version) {
  const tmp = file.replace(/\.mp4$/, '.stamped.mp4');
  const args = [
    '-v', 'error', '-y', '-i', file, '-c', 'copy',
    '-metadata', `title=${AI_ID_TITLE}`,
    '-metadata', `artist=${AI_ID_ARTIST}`,
    '-metadata', `comment=AI-generated video — ${AI_ID_TITLE} via ${AI_ID_ARTIST} v${version || '1.0.0'}`,
    '-metadata', 'description=Generated by the MiniMax H3 model on a Kaggle GPU',
    '-movflags', '+faststart',
    tmp,
  ];
  const r = exec('ffmpeg', args, { timeout: 120000 });
  if (r && r.status === 0 && fs.existsSync(tmp) && fs.statSync(tmp).size > 0) {
    fs.renameSync(tmp, file);
    return true;
  }
  try { if (fs.existsSync(tmp)) fs.unlinkSync(tmp); } catch (e) { /* nothing to clean */ }
  return false;
}

function defaultExec(cmd, args, opts) {
  return spawnSync(cmd, args, opts);
}

function tailLines(text, n) {
  const clean = String(text || '').replace(/\u001b\[[0-9;?]*[A-Za-z]/g, '');
  const lines = clean.split(/\r?\n/).filter((l) => l.length);
  return lines.slice(-n);
}

// FL8: bytes free from `df -Pk <dir>`. Injectable so failure drills need no
// real full disk. Returns null when df cannot be read (never a hard failure).
function humanBytes(bytes) {
  const mb = bytes / 1048576;
  if (mb >= 1024) return `${(mb / 1024).toFixed(1)} GB`;
  return `${Math.round(mb)} MB`;
}

function defaultFreeBytes(dir, exec) {
  let r;
  try { r = exec('df', ['-Pk', dir], { encoding: 'utf8' }); } catch (e) { return null; }
  if (!r || r.status !== 0) return null;
  const lines = String(r.stdout || '').trim().split(/\r?\n/).filter((l) => l);
  if (!lines.length) return null;
  const cols = lines[lines.length - 1].trim().split(/\s+/);
  const kb = Number(cols[3]);
  return Number.isFinite(kb) ? kb * 1024 : null;
}

function createPipeline(config, base, deps) {
  const d = deps || {};
  const exec = d.exec || defaultExec;
  const kaggle = d.kaggle || createClient(config);
  const freeBytes = d.freeBytes || ((dir) => defaultFreeBytes(dir, exec));
  // The engine is part of the app, never an operator-supplied path outside it.
  const engineDir = path.resolve(config.engine_dir || path.join(__dirname, '..', 'engine'));
  const runPath = (tag, ...parts) => path.join(base, 'data', 'runs', tag, ...parts);
  // Kernel output is downloaded nested inside raw/; publish flattens clips into out/.
  const outDir = (tag) => runPath(tag, 'raw');
  const servedDir = (tag) => runPath(tag, 'out');
  const donePath = (tag) => runPath(tag, 'done');

  let ownerCache = config.owner || null;
  function owner() {
    if (!ownerCache && kaggle.username) ownerCache = kaggle.username();
    return ownerCache || '';
  }

  const env = () => {
    const e = childEnv(config, config.kaggle_bin);
    e.H3_ENGINE_ROOT = engineDir;
    if (config.kernel_prefix) e.KERNEL_PREFIX = config.kernel_prefix;
    const who = owner();
    if (who) e.KAGGLE_OWNER = who;
    return e;
  };

  function sh(cmd, args, timeoutMs) {
    const r = exec(cmd, args, {
      cwd: engineDir, env: env(), encoding: 'utf8', timeout: timeoutMs || 5 * 60 * 1000,
    });
    if (r && r.error) {
      return { status: -1, output: String(r.error), error: String(r.error) };
    }
    const output = ((r && r.stdout) || '') + ((r && r.stderr) || '');
    return {
      status: r && r.status != null ? r.status : -1,
      output: output.trim(),
      error: r && r.status !== 0 ? output.trim() : null,
    };
  }

  // STAGING — idempotent. Prompt files are regenerated from the immutable request.
  function stage(tag, slots) {
    fs.mkdirSync(runPath(tag), { recursive: true });
    const r0 = sh('python3', ['stage_shot.py', '--tag', tag, '--reset'], 3 * 60 * 1000);
    if (r0.status !== 0) return { ok: false, status: r0.status, output: r0.output, error: r0.error };
    const chunks = [r0.output];
    for (const slot of slots) {
      const promptFile = runPath(tag, `slot${slot.n}.txt`);
      fs.writeFileSync(promptFile, String(slot.prompt) + '\n');
      const args = [
        'stage_shot.py', '--tag', tag, '--id', slot.id,
        '--seconds', String(slot.seconds), '--prompt-file', promptFile,
        '--seed', String(813001 + slot.n - 1),
      ];
      if (slot.image) {
        const img = path.isAbsolute(slot.image) ? slot.image : runPath(tag, slot.image);
        args.push('--image', img);
      }
      const r = sh('python3', args, 3 * 60 * 1000);
      chunks.push(r.output);
      if (r.status !== 0) {
        return { ok: false, status: r.status, output: chunks.join('\n'), error: r.error };
      }
    }
    return { ok: true, status: 0, output: chunks.join('\n'), error: null };
  }

  // GATING + BUILDING + PUSH — one script, never auto-retried (D1).
  function push(tag) {
    const r = sh('./run_six.sh', [tag, '--no-wait'], 5 * 60 * 1000);
    const logDir = runPath(tag, 'logs');
    fs.mkdirSync(logDir, { recursive: true });
    fs.writeFileSync(path.join(logDir, 'push.log'), r.output + '\n');
    const preflight = (r.output.match(/PREFLIGHT FAIL:[^\r\n]*/) || [])[0] || null;
    return {
      ok: r.status === 0,
      status: r.status,
      output: r.output,
      error: r.error,
      preflight,
    };
  }

  // POLL — delegates to the kaggle client so fixtures can inject statuses.
  function poll(ref, opts) {
    return kaggle.status(ref, opts);
  }

  // COLLECT — flock-guarded so the cron watcher and the app cannot interleave.
  function collect(tag, opts) {
    // FL8: refuse to start a download that cannot fit. Clips already on disk
    // are left untouched; the worker turns this into a FAILED state.
    const needBytes = opts && opts.needBytes;
    if (needBytes) {
      const avail = freeBytes(engineDir);
      if (avail != null && avail < needBytes) {
        return {
          ok: false, busy: false, status: 1, disk: true,
          disk_avail_bytes: avail, disk_need_bytes: needBytes,
          output: '',
          error: `not enough disk (${humanBytes(avail)} free, needed ~${humanBytes(needBytes)}).`,
        };
      }
    }
    const lock = path.join(base, 'data', 'locks', tag + '.lock');
    fs.mkdirSync(path.dirname(lock), { recursive: true });
    const r = sh('flock', ['-n', lock, './collect_run.sh', tag, '--no-pi'], 10 * 60 * 1000);
    // flock -n exits 1 when another holder has the lock: retry next tick, not a failure.
    if (r.status === 1 && /could not lock|would block/i.test(r.output)) {
      return { ok: false, busy: true, status: 1, output: r.output };
    }
    return {
      ok: r.status === 0,
      busy: false,
      status: r.status,
      output: r.output,
      error: r.status === 0 ? null : r.output,
    };
  }

  function walk(dir) {
    const found = [];
    if (!fs.existsSync(dir)) return found;
    for (const e of fs.readdirSync(dir, { withFileTypes: true })) {
      const p = path.join(dir, e.name);
      if (e.isDirectory()) found.push(...walk(p));
      else found.push(p);
    }
    return found;
  }

  // VERIFY + PUBLISH — truth comes from results.json and the kernel log, never
  // from the mere fact that Kaggle said COMPLETE (SPEC §9, FL5).
  function publish(tag, request) {
    const src = outDir(tag);
    const files = walk(src);
    const resultFiles = files.filter((f) => /_results\.json$/.test(f)).sort();
    let results = [];
    for (const f of resultFiles) {
      try {
        const parsed = JSON.parse(fs.readFileSync(f, 'utf8'));
        if (Array.isArray(parsed) && parsed.length > results.length) results = parsed;
      } catch (e) { /* a partial file from a dead kernel is ignored */ }
    }

    const logFiles = files.filter((f) => /\.log$/.test(f)).sort();
    const logText = logFiles.map((f) => fs.readFileSync(f, 'utf8')).join('\n');
    const probe = logText.match(/PROBE RENDERED\s+(\d+)\s*\/\s*(\d+)/);
    const rendered = probe
      ? { ok: Number(probe[1]), total: Number(probe[2]) }
      : { ok: 0, total: (request && request.slots ? request.slots.length : 0) };
    const fails = {};
    for (const m of logText.matchAll(/^\s*FAIL\s+(\S+)\s+(.*)$/gm)) fails[m[1]] = m[2].trim();
    for (const r of results) {
      if (!r.files || !r.files.length) fails[r.id] = String(r.error || 'no output file').slice(0, 400);
    }

    const dst = servedDir(tag);
    fs.mkdirSync(dst, { recursive: true });
    const published = [];
    for (const f of files) {
      if (!/\.(mp4|png)$/.test(f)) continue;
      let name = path.basename(f);
      let target = path.join(dst, name);
      if (fs.existsSync(target)) {
        name = path.basename(path.dirname(f)) + '_' + name;
        target = path.join(dst, name);
      }
      fs.copyFileSync(f, target);
      let stamped = null;
      if (name.endsWith('.mp4')) stamped = stampMp4(target, exec, config.version);
      published.push({
        name,
        bytes: fs.statSync(target).size,
        kind: name.endsWith('.mp4') ? 'video' : 'sheet',
        ai_identifier: name.endsWith('.mp4') ? Boolean(stamped) : null,
      });
    }

    const byId = new Map(results.map((r) => [r.id, r]));
    const slotResults = [];
    const slots = (request && request.slots) || [];
    for (const slot of slots) {
      const r = byId.get(slot.id);
      const file = r && r.files && r.files.length
        ? published.find((p) => p.name === path.basename(r.files[0]))
        : null;
      slotResults.push({
        n: slot.n,
        id: slot.id,
        result: file ? 'ok' : 'failed',
        wall_seconds: r && r.wall_seconds != null ? r.wall_seconds : null,
        error: fails[slot.id] || (r ? r.error : null) || null,
        file: file ? file.name : null,
        sheet: file ? published.find((p) => p.name === path.basename(r.files[0]).replace(/\.mp4$/, '_sheet.png'))?.name || null : null,
      });
    }
    return {
      results,
      rendered,
      fails,
      files: published,
      slotResults,
      logText,
      logTail: tailLines(logText, 40),
      resultsCount: results.length,
    };
  }

  function writeDone(tag, content) {
    fs.writeFileSync(donePath(tag), (content || 'done') + '\n');
  }
  function doneExists(tag) { return fs.existsSync(donePath(tag)); }

  return {
    stage, push, poll, collect, publish, writeDone, doneExists,
    outDir, servedDir, donePath, runPath, sh, engineDir, owner,
    client: kaggle,
  };
}

module.exports = { createPipeline, tailLines, humanBytes, defaultFreeBytes };
